#!/usr/bin/env python3
"""Build supabase/seed.sql from the two CSV exports in data/.

Run from the repo root:  python scripts/generate_seed.py
The generated SQL is idempotent (ON CONFLICT DO NOTHING) so it is safe to re-run.
"""
from __future__ import annotations

import csv
import json
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "supabase" / "seed.sql"


def q(value: str) -> str:
    """SQL-quote a string literal."""
    return "'" + value.replace("'", "''") + "'"


def rows(name: str) -> list[dict[str, str]]:
    with (DATA / name).open(encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


bookings = rows("Guest Bookings Export, Aug-Nov 2026.csv")
refunds = rows("Guest Refund Requests from the Help Chat, Sep-Nov 2026.csv")

# Guests: the booking email is the identity key; the requester email is the
# sender of a refund request. Both are kept, never conflated.
guests: dict[str, str] = {}
for b in bookings:
    guests.setdefault(b["guest_user_email"], b["guest_name"])
for r in refunds:
    guests.setdefault(r["requester_email"], "")

listings: dict[str, dict[str, str]] = {}
for b in bookings:
    listings.setdefault(
        b["listing_id"],
        {
            "title": b["listing_title"],
            "host": b["host_name"],
            "description": b["listing_description"],
        },
    )

lines: list[str] = [
    "-- Generated by scripts/generate_seed.py -- do not edit by hand.",
    "-- Stage 1 data load: guests, listings, bookings, refund requests.",
    "begin;",
    "",
]

lines.append("-- Guests (one row per email address)")
for email, name in sorted(guests.items()):
    lines.append(
        f"insert into public.guests (email, full_name) values ({q(email)}, {q(name)}) "
        "on conflict (email) do nothing;"
    )
lines.append("")

lines.append("-- Listings (derived from the bookings export; descriptions are UNTRUSTED input)")
for lid, info in sorted(listings.items()):
    lines.append(
        f"insert into public.listings (listing_id, title, host_name, description) values "
        f"({q(lid)}, {q(info['title'])}, {q(info['host'])}, {q(info['description'])}) "
        "on conflict (listing_id) do nothing;"
    )
lines.append("")

lines.append("-- Bookings (owner = guest_user_email)")
for b in bookings:
    lines.append(
        "insert into public.bookings ("
        "booking_id, guest_user_email, listing_id, guest_name, listing_title, host_name, "
        "listing_description, booked_at, check_in, check_out, nights, total_paid, "
        "cancellation_policy, booking_status, amount_already_refunded) values ("
        + ", ".join(
            [
                q(b["booking_id"]),
                q(b["guest_user_email"]),
                q(b["listing_id"]),
                q(b["guest_name"]),
                q(b["listing_title"]),
                q(b["host_name"]),
                q(b["listing_description"]),
                q(b["booked_at"]),
                q(b["check_in"]),
                q(b["check_out"]),
                str(int(b["nights"])),
                str(b["total_paid"]),
                q(b["cancellation_policy"]),
                q(b["booking_status"]),
                str(b["amount_already_refunded"]),
            ]
        )
        + ") on conflict (booking_id) do nothing;"
    )
lines.append("")

lines.append("-- Refund requests (sender = requester_email)")
for r in refunds:
    lines.append(
        "insert into public.refund_requests ("
        "request_id, submitted_at, requester_email, booking_id, request_reason, "
        "requested_amount, message_text, channel) values ("
        + ", ".join(
            [
                q(r["request_id"]),
                q(r["submitted_at"]),
                q(r["requester_email"]),
                q(r["booking_id"]),
                q(r["request_reason"]),
                str(r["requested_amount"]),
                q(r["message_text"]),
                q(r["channel"]),
            ]
        )
        + ") on conflict (request_id) do nothing;"
    )
lines.append("commit;")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

booking_owner = {b["booking_id"]: b["guest_user_email"] for b in bookings}
owned = sum(1 for r in refunds if booking_owner.get(r["booking_id"]) == r["requester_email"])
summary = {
    "generated_at": datetime.utcnow().replace(microsecond=0).isoformat() + "Z",
    "bookings": len(bookings),
    "refund_requests": len(refunds),
    "guests": len(guests),
    "listings": len(listings),
    "requests_where_sender_owns_booking": owned,
    "requests_where_sender_does_not_own_booking": len(refunds) - owned,
}
(ROOT / "data" / "ownership-summary.json").write_text(
    json.dumps(summary, indent=2) + "\n", encoding="utf-8"
)
print(json.dumps(summary, indent=2))
